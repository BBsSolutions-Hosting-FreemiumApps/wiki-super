// Build a Worker and a content-versioned KV package. This does not deploy.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(process.argv[2]||path.join(__dirname,'..'));
const sha=x=>crypto.createHash('sha256').update(x).digest('hex');
const data=fs.readdirSync(path.join(root,'data')).filter(f=>/^[a-z0-9]+\.json$/.test(f)).sort();
const hashes=Object.fromEntries(data.map(f=>[f,sha(fs.readFileSync(path.join(root,'data',f)))]));
const prefix='rtf-'+sha(JSON.stringify(hashes)).slice(0,20)+'/';
const files={'/index.html':['text/html; charset=utf-8','site/index.html'],'/style.css':['text/css; charset=utf-8','site/style.css'],'/rtf.css':['text/css; charset=utf-8','site/rtf.css'],'/app.js':['application/javascript; charset=utf-8','site/app.js']};
const assets={};
for(const [p,[t,f]] of Object.entries(files)) assets[p]=[t,fs.readFileSync(path.join(root,f),'utf8')];
for(const asset of ['/app.js','/style.css','/rtf.css']){
  const re=new RegExp(asset.replace('.','\\.')+'(?:\\?v=[^"\\s]+)?','g');
  assets['/index.html'][1]=assets['/index.html'][1].replace(re,asset+'?v='+sha(assets[asset][1]).slice(0,16));
}
const src=`// Generated by build/make_worker.js. No credentials.
const ASSETS=${JSON.stringify(assets)};
const PREFIX=${JSON.stringify(prefix)};
const SEC={'X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer','Content-Security-Policy':"default-src 'self'; img-src 'self' data:; style-src 'self'; script-src 'self'; connect-src 'self'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'"};
function headers(h,host){const o={...SEC,...h};if(host.endsWith('.workers.dev'))o['X-Robots-Tag']='noindex, nofollow';return o}
export default {
 async fetch(req,env){
  const u=new URL(req.url), host=u.hostname;
  if(req.method!=='GET'&&req.method!=='HEAD')return new Response('Methode niet toegestaan',{status:405,headers:headers({'Allow':'GET, HEAD'},host)});
  const p=u.pathname==='/'?'/index.html':u.pathname;
  if(p==='/favicon.ico')return new Response(null,{status:204,headers:headers({},host)});
  if(p==='/robots.txt')return new Response(req.method==='HEAD'?null:(host.endsWith('.workers.dev')?'User-agent: *\\nDisallow: /\\n':'User-agent: *\\nAllow: /\\n'),{headers:headers({'Content-Type':'text/plain; charset=utf-8'},host)});
  if(p==='/version.json')return Response.json({prefix:PREFIX},{headers:headers({'Cache-Control':'no-cache'},host)});
  if(ASSETS[p]){const [t,b]=ASSETS[p];return new Response(req.method==='HEAD'?null:b,{headers:headers({'Content-Type':t,'Cache-Control':p==='/index.html'?'no-cache':'public, max-age=3600'},host)})}
  const m=/^\\/data\\/([a-z0-9]+\\.json)$/.exec(p);
  if(m){
   const b=await env.DATA.get(PREFIX+m[1],{type:'stream',cacheTtl:3600});
   if(b===null)return Response.json({fout:'niet gevonden'},{status:404,headers:headers({},host)});
   return new Response(req.method==='HEAD'?null:b,{headers:headers({'Content-Type':'application/json; charset=utf-8','Cache-Control':'public, max-age=3600'},host)});
  }
  return new Response('Niet gevonden',{status:404,headers:headers({'Content-Type':'text/plain; charset=utf-8'},host)});
 }
};\n`;
fs.mkdirSync(path.join(root,'worker'),{recursive:true});
fs.writeFileSync(path.join(root,'worker','worker.mjs'),src);
fs.writeFileSync(path.join(root,'worker','release.json'),JSON.stringify({prefix,files:hashes},null,2)+'\n');
console.log(prefix,data.length+' data files',Buffer.byteLength(src)+' Worker bytes');
